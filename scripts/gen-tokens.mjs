#!/usr/bin/env node
/**
 * Generates src/app/tokens.css from the colour table below (X02-FR-1/2).
 *
 * Why a generator: modern-web-guidance (dark-mode) requires each token to exist as raw light/dark
 * values, a `light-dark()` combination, AND a `prefers-color-scheme` fallback for browsers without
 * `light-dark()` (Next 16 supports Safari 16.4+, light-dark() needs 17.5). Writing three copies of ~35
 * tokens by hand invites drift; this keeps one source. Run: `node scripts/gen-tokens.mjs`.
 */
import { writeFileSync } from "node:fs";

// name: [light, dark]. Text colours meet WCAG AA (4.5:1) on --bg/--surface in both schemes.
const colors = {
  bg: ["#fafafa", "#111215"],
  surface: ["#ffffff", "#16181c"],
  raised: ["#ffffff", "#1c1f24"],
  fg: ["#17191d", "#e5e7ea"],
  muted: ["#545b66", "#a2a8b1"],
  faint: ["#666d77", "#8b929c"],
  line: ["#e8e9ec", "#25292f"],
  "line-strong": ["#d3d6db", "#353a42"],
  accent: ["#2c56c9", "#86a5ff"],
  "accent-fg": ["#ffffff", "#0d1426"],
  "accent-soft": ["#eaeffb", "#1a2440"],
  "code-bg": ["#f2f3f5", "#1b1e23"],
  mark: ["#fff1b8", "#4a3d0c"],
  ok: ["#1d7448", "#55c48f"],
  "ok-soft": ["#e2f2e9", "#13281d"],
  warn: ["#8f5a00", "#e2a740"],
  "warn-soft": ["#fbefd6", "#2b2111"],
  err: ["#b3261e", "#ff8076"],
  "err-soft": ["#fce8e6", "#341716"],
  edge: ["#cfd3d9", "#3a3f47"],
  "edge-sug": ["#b9bec6", "#4a505a"],
  "shadow-1": ["rgba(20, 24, 32, 0.05)", "rgba(0, 0, 0, 0.4)"],
  "shadow-2": ["rgba(20, 24, 32, 0.07)", "rgba(0, 0, 0, 0.45)"],
  // Topic palette: topics are open-ended, so a topic's colour is picked by hashing its slug into these.
  "t-1": ["#3567d6", "#7ea3ff"],
  "t-2": ["#0b8a78", "#3fcab4"],
  "t-3": ["#c25e08", "#f0a35c"],
  "t-4": ["#8648cf", "#b893f4"],
  "t-5": ["#c4365a", "#f57f9b"],
  "t-6": ["#5a861a", "#a0cc5f"],
  "t-7": ["#0e7490", "#4cc3dc"],
  "t-8": ["#9a6b00", "#e0b44a"],
};

const raw = Object.entries(colors)
  .map(([name, [l, d]]) => `  --${name}-l: ${l};\n  --${name}-d: ${d};`)
  .join("\n");
const light = Object.keys(colors).map((n) => `  --${n}: var(--${n}-l);`).join("\n");
const dark = Object.keys(colors).map((n) => `    --${n}: var(--${n}-d);`).join("\n");
const ld = Object.keys(colors).map((n) => `    --${n}: light-dark(var(--${n}-l), var(--${n}-d));`).join("\n");

const css = `/* GENERATED by scripts/gen-tokens.mjs — edit the table there, then re-run. */
:root {
${raw}

  /* Fallback for browsers without light-dark(): follow the system preference only. */
${light}
  --shadow: 0 1px 2px var(--shadow-1), 0 8px 24px var(--shadow-2);
}
@media (prefers-color-scheme: dark) {
  :root {
${dark}
  }
}
@supports (color: light-dark(white, black)) {
  :root {
${ld}
  }
}

/* The site follows the system scheme; the header toggle pins an override through the
   <meta name="color-scheme"> element (modern-web-guidance: dark-mode-toggle). CSS maps the meta back
   to the property so light-dark() follows it. The base value MUST stay "light dark". */
:root {
  color-scheme: light dark;
}
:root:has(> head > meta[name="color-scheme"][content="dark"]) {
  color-scheme: dark;
}
:root:has(> head > meta[name="color-scheme"][content="light"]) {
  color-scheme: light;
}
`;

writeFileSync(new URL("../src/app/tokens.css", import.meta.url), css);
console.log("wrote src/app/tokens.css");
