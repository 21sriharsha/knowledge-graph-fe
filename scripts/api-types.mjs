#!/usr/bin/env node
/**
 * Generates `src/lib/api/schema.d.ts` from the backend OpenAPI spec (ADR 0007).
 *
 *   pnpm api:types          regenerate the committed types
 *   pnpm api:types --check  fail (exit 1) when the committed types differ from the spec (CI drift check)
 *
 * The spec path defaults to the sibling backend checkout; override with API_SPEC_PATH (CI checks the
 * backend repo out next to this one). Uses openapi-typescript's Node API so no shell is involved.
 */
import { readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { resolve } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const specPath = resolve(process.env.API_SPEC_PATH ?? "../knowledge-graph-be/apim/api-spec.yaml");
const outPath = resolve("src/lib/api/schema.d.ts");
const check = process.argv.includes("--check");

if (!existsSync(specPath)) {
  console.error(`[api-types] spec not found at ${specPath}. Set API_SPEC_PATH.`);
  process.exit(2);
}

const header =
  "/**\n * GENERATED by scripts/api-types.mjs from apim/api-spec.yaml — do not edit by hand.\n */\n\n";
const ast = await openapiTS(new URL(`file://${specPath}`));
const generated = header + astToString(ast);

if (check) {
  const current = existsSync(outPath) ? await readFile(outPath, "utf8") : "";
  if (current !== generated) {
    console.error("[api-types] schema.d.ts is out of date with the spec. Run `pnpm api:types`.");
    process.exit(1);
  }
  console.log("[api-types] schema.d.ts matches the spec.");
} else {
  await writeFile(outPath, generated);
  console.log(`[api-types] wrote ${outPath}`);
}
